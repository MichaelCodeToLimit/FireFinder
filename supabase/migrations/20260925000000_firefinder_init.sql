-- Candidate retrieval for search and duplicate detection.
-- Hybrid: nearest neighbours by embedding UNION exact error-code matches.
-- Final ranking happens in the API (packages/core/src/ranking.ts) so it can
-- evolve without migrations.
create or replace function firefinder.search_candidates(
  p_embedding extensions.vector(384),
  p_error_signature text[],
  p_limit integer,
  p_solution_embedding extensions.vector(384) default null
)
returns table (
  id uuid,
  fire_number bigint,
  problem text,
  solution text,
  software text,
  operating_system text,
  software_version text,
  error_message text,
  software_key text,
  os_family text,
  os_version text,
  version_major text,
  error_signature text[],
  confirmation_count integer,
  failure_count integer,
  status text,
  verification_status text,
  created_at timestamptz,
  updated_at timestamptz,
  last_confirmed_at timestamptz,
  last_failed_at timestamptz,
  similarity double precision,
  solution_similarity double precision,
  error_overlap integer
)
language sql
stable
set search_path = ''
-- HNSW returns at most ef_search rows; keep it above any candidate limit we use.
set hnsw.ef_search = '100'
as $$
  with semantic as (
    select s.id
    from firefinder.solutions s
    where s.status <> 'disabled'
    order by s.embedding operator(extensions.<=>) p_embedding
    limit least(p_limit, 100)
  ),
  lexical as (
    select s.id
    from firefinder.solutions s
    where cardinality(p_error_signature) > 0
      and s.error_signature && p_error_signature
      and s.status <> 'disabled'
    order by s.confirmation_count desc
    limit least(p_limit, 100)
  ),
  candidate_ids as (
    select semantic.id from semantic
    union
    select lexical.id from lexical
  )
  select
    s.id, s.fire_number, s.problem, s.solution,
    s.software, s.operating_system, s.software_version, s.error_message,
    s.software_key, s.os_family, s.os_version, s.version_major, s.error_signature,
    s.confirmation_count, s.failure_count, s.status, s.verification_status,
    s.created_at, s.updated_at, s.last_confirmed_at, s.last_failed_at,
    1 - (s.embedding operator(extensions.<=>) p_embedding) as similarity,
    case
      when p_solution_embedding is null then null
      else 1 - (s.solution_embedding operator(extensions.<=>) p_solution_embedding)
    end as solution_similarity,
    cardinality(array(
      select unnest(s.error_signature)
      intersect
      select unnest(p_error_signature)
    )) as error_overlap
  from candidate_ids c
  join firefinder.solutions s on s.id = c.id;
$$;

-- Record "worked" / "failed" feedback atomically.
-- * One vote per voter per solution; a voter may change their vote.
-- * Counters, last_confirmed_at and last_failed_at are updated together.
-- * Moderation hook: a solution that keeps failing is moved to under_review.
--   It is never deleted automatically; a fix may only fail in some environments.
create or replace function firefinder.record_feedback(
  p_solution_id uuid,
  p_result text,
  p_voter_hash text,
  p_operating_system text default null,
  p_software_version text default null,
  p_note text default null,
  p_review_min_failures integer default 5,
  p_review_failure_ratio double precision default 0.75
)
returns table (outcome text, previous_result text)
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_status text;
  v_vote_id bigint;
  v_previous text;
begin
  if p_result is null or p_result not in ('worked', 'failed') then
    raise exception 'invalid feedback result: %', p_result using errcode = '22023';
  end if;

  -- Lock the solution row: serializes feedback per solution, so counters and
  -- the one-vote-per-voter rule stay consistent under concurrency.
  select s.status into v_status
  from firefinder.solutions s
  where s.id = p_solution_id
  for update;

  if not found or v_status = 'disabled' then
    return query select 'not_found'::text, null::text;
    return;
  end if;

  if p_voter_hash is not null then
    select c.id, c.result into v_vote_id, v_previous
    from firefinder.solution_confirmations c
    where c.solution_id = p_solution_id and c.voter_hash = p_voter_hash;
  end if;

  if v_previous = p_result then
    return query select 'duplicate'::text, v_previous;
    return;
  end if;

  if v_vote_id is not null then
    update firefinder.solution_confirmations c
    set result = p_result,
        operating_system = p_operating_system,
        software_version = p_software_version,
        note = p_note,
        updated_at = now()
    where c.id = v_vote_id;
  else
    insert into firefinder.solution_confirmations
      (solution_id, result, voter_hash, operating_system, software_version, note)
    values
      (p_solution_id, p_result, p_voter_hash, p_operating_system, p_software_version, p_note);
  end if;

  update firefinder.solutions s
  set confirmation_count = s.confirmation_count
        + (case when p_result = 'worked' then 1 else 0 end)
        - (case when v_previous = 'worked' then 1 else 0 end),
      failure_count = s.failure_count
        + (case when p_result = 'failed' then 1 else 0 end)
        - (case when v_previous = 'failed' then 1 else 0 end),
      last_confirmed_at = case when p_result = 'worked' then now() else s.last_confirmed_at end,
      last_failed_at = case when p_result = 'failed' then now() else s.last_failed_at end
  where s.id = p_solution_id;

  update firefinder.solutions s
  set status = 'under_review'
  where s.id = p_solution_id
    and s.status = 'active'
    and s.failure_count >= p_review_min_failures
    and s.failure_count::double precision
        / (s.failure_count + s.confirmation_count) >= p_review_failure_ratio;

  return query
    select (case when v_previous is null then 'recorded' else 'changed' end)::text, v_previous;
end;
$$;

-- Fixed-window rate limit counter. Returns the number of hits in the current
-- window including this one.
create or replace function firefinder.rate_limit_hit(
  p_key text,
  p_window_seconds integer
)
returns integer
language plpgsql
volatile
set search_path = ''
as $$
declare
  v_window timestamptz :=
    to_timestamp(floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds);
  v_hits integer;
begin
  insert into firefinder.rate_limit_buckets as b (bucket_key, window_start, hits)
  values (p_key, v_window, 1)
  on conflict (bucket_key, window_start) do update set hits = b.hits + 1
  returning b.hits into v_hits;

  -- Opportunistic cleanup keeps the table tiny without needing a cron job.
  if random() < 0.01 then
    delete from firefinder.rate_limit_buckets
    where window_start < now() - interval '1 hour';
  end if;

  return v_hits;
end;
$$;

-- =============================================================================
-- Security
-- =============================================================================

-- Row-level security as defense in depth. There are deliberately no policies:
-- any role other than the owner (the API) sees nothing.
alter table firefinder.solutions enable row level security;
alter table firefinder.solution_confirmations enable row level security;
alter table firefinder.api_keys enable row level security;
alter table firefinder.rate_limit_buckets enable row level security;

-- Functions are executable by PUBLIC by default in Postgres; revoke that.
revoke all on schema firefinder from public;
revoke execute on all functions in schema firefinder from public;
alter default privileges in schema firefinder revoke execute on functions from public;

do $$
begin
  -- Supabase Data API roles: no access to anything FireFinder stores.
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on schema firefinder from anon';
    execute 'revoke all on all tables in schema firefinder from anon';
    execute 'revoke all on all functions in schema firefinder from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on schema firefinder from authenticated';
    execute 'revoke all on all tables in schema firefinder from authenticated';
    execute 'revoke all on all functions in schema firefinder from authenticated';
  end if;
end;
$$;
