-- =============================================================================
-- FireFinder schema
-- Solve a problem once -> remember the solution -> help everyone who hits it.
--
-- Portable by design: plain PostgreSQL 15+ with pgvector >= 0.7. Nothing here
-- depends on Supabase, but when Supabase's Data API roles (anon, authenticated)
-- exist they are explicitly locked out. All access goes through the FireFinder
-- API, which connects as the schema owner.
--
-- The script is idempotent so it can be applied by `supabase db push` or by
-- `npm run db:migrate` (self-hosted) without conflict.
-- =============================================================================

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

-- A dedicated schema keeps FireFinder out of Supabase's auto-generated REST API
-- (which only exposes `public` by default).
create schema if not exists firefinder;
comment on schema firefinder is
  'FireFinder shared solution memory. Accessed only through the FireFinder API.';

-- -----------------------------------------------------------------------------
-- solutions: one verified (or candidate) problem/solution pair, a "fire".
-- -----------------------------------------------------------------------------
create table if not exists firefinder.solutions (
  -- UUIDv7 generated by the API so records stay globally unique across
  -- self-hosted instances and future community mirrors.
  id uuid primary key default gen_random_uuid(),
  -- Short human-friendly number used in the UI: "FIRE #18492".
  fire_number bigint generated always as identity unique,

  problem text not null,
  solution text not null,
  software text,
  operating_system text,
  software_version text,
  error_message text,

  -- Normalized metadata computed by the API and used for matching/ranking.
  software_key text,
  os_family text,
  os_version text,
  version_major text,
  error_signature text[] not null default '{}',

  confirmation_count integer not null default 0,
  failure_count integer not null default 0,
  -- Moderation state. Disabled solutions are never returned.
  status text not null default 'active',
  -- A submission is only a candidate until at least one person confirms it.
  verification_status text generated always as (
    case when confirmation_count > 0 then 'verified' else 'candidate' end
  ) stored,

  -- gte-small embedding of the problem (+ error, software) for semantic search.
  embedding extensions.vector(384) not null,
  -- gte-small embedding of the solution text, used for duplicate detection.
  solution_embedding extensions.vector(384) not null,
  embedding_model text not null,
  -- Which integration submitted it (e.g. "claude-mcp"). Never a person.
  source text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_confirmed_at timestamptz,
  last_failed_at timestamptz,

  constraint solutions_problem_length check (char_length(problem) between 3 and 1000),
  constraint solutions_solution_length check (char_length(solution) between 3 and 5000),
  constraint solutions_software_length check (char_length(software) <= 100),
  constraint solutions_os_length check (char_length(operating_system) <= 100),
  constraint solutions_version_length check (char_length(software_version) <= 50),
  constraint solutions_error_length check (char_length(error_message) <= 1000),
  constraint solutions_source_length check (char_length(source) <= 40),
  constraint solutions_status_check check (status in ('active', 'under_review', 'disabled')),
  constraint solutions_counts_nonnegative check (confirmation_count >= 0 and failure_count >= 0),
  constraint solutions_error_signature_size check (cardinality(error_signature) <= 16)
);

comment on table firefinder.solutions is
  'Problem/solution pairs. Only generalized, privacy-filtered text is stored; never conversations.';

-- Approximate nearest-neighbour search on the problem embedding.
create index if not exists solutions_embedding_hnsw_idx
  on firefinder.solutions using hnsw (embedding extensions.vector_cosine_ops);

-- Exact error-code matching (ERR_OSSL_EVP_UNSUPPORTED, 0x80070005, ...).
create index if not exists solutions_error_signature_idx
  on firefinder.solutions using gin (error_signature);

-- Moderation queue: the (small) set of solutions that are not active.
create index if not exists solutions_moderation_idx
  on firefinder.solutions (status, updated_at desc)
  where status <> 'active';

create or replace function firefinder.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace trigger solutions_touch_updated_at
  before update on firefinder.solutions
  for each row execute function firefinder.touch_updated_at();

-- -----------------------------------------------------------------------------
-- solution_confirmations: one row per "it worked" / "it didn't work" vote.
-- voter_hash is an HMAC of an anonymous client identifier: it lets us count
-- one vote per voter without knowing who anyone is.
-- -----------------------------------------------------------------------------
create table if not exists firefinder.solution_confirmations (
  id bigint generated always as identity primary key,
  solution_id uuid not null references firefinder.solutions (id) on delete cascade,
  result text not null,
  voter_hash text,
  -- Optional environment of the voter; helps moderators see *where* a fix fails.
  operating_system text,
  software_version text,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint confirmations_result_check check (result in ('worked', 'failed')),
  constraint confirmations_voter_hash_format check (voter_hash ~ '^[0-9a-f]{64}$'),
  constraint confirmations_os_length check (char_length(operating_system) <= 100),
  constraint confirmations_version_length check (char_length(software_version) <= 50),
  constraint confirmations_note_length check (char_length(note) <= 500)
);

-- Foreign-key index; also serves "latest feedback for a solution".
create index if not exists solution_confirmations_solution_idx
  on firefinder.solution_confirmations (solution_id, created_at desc);

-- One vote per anonymous voter per solution.
create unique index if not exists solution_confirmations_voter_idx
  on firefinder.solution_confirmations (solution_id, voter_hash)
  where voter_hash is not null;

-- -----------------------------------------------------------------------------
-- api_keys: server-to-server credentials. Only a SHA-256 hash is stored.
-- -----------------------------------------------------------------------------
create table if not exists firefinder.api_keys (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  key_prefix text not null,
  key_hash text not null unique,
  scopes text[] not null default array['read', 'write'],
  created_at timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at timestamptz,

  constraint api_keys_name_length check (char_length(name) between 1 and 100),
  constraint api_keys_hash_format check (key_hash ~ '^[0-9a-f]{64}$'),
  constraint api_keys_scopes_check check (
    cardinality(scopes) > 0 and scopes <@ array['read', 'write', 'admin']
  )
);

-- -----------------------------------------------------------------------------
-- rate_limit_buckets: fixed-window counters for the Postgres-backed limiter
-- (used where the API runs as many short-lived instances, e.g. Edge Functions).
-- Unlogged: fast, and losing counters on a crash is harmless.
-- -----------------------------------------------------------------------------
create unlogged table if not exists firefinder.rate_limit_buckets (
  bucket_key text not null,
  window_start timestamptz not null,
  hits integer not null default 0,
  primary key (bucket_key, window_start)
);

